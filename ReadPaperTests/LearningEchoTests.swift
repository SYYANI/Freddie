import XCTest
@testable import ReadPaper

@MainActor
final class LearningEchoTests: XCTestCase {
    private let mai = UUID()
    private let collapse = UUID()
    private let transformer = UUID()
    private let current = UUID()

    private func event(
        _ id: String,
        _ kind: LearningEvent.Kind,
        paper: UUID,
        page: Int? = 1,
        quote: String?,
        text: String? = nil,
        at seconds: TimeInterval = 100,
        writingID: UUID? = nil,
        subject: String? = nil
    ) -> LearningEvent {
        LearningEvent(
            id: id, subject: subject ?? id, paperID: paper, kind: kind,
            occurredAt: Date(timeIntervalSince1970: seconds), isBackfilled: false,
            pageIndex: page, quote: quote, text: text, writingID: writingID
        )
    }

    /// A small library of past actions on unrelated topics, so term weights look like a
    /// real reader's.
    private var library: [LearningEvent] {
        [
            event(
                "synthetic", .highlight, paper: mai,
                quote: "We choose not to use any synthetic data generated by language models during pretraining, and work to avoid and remove AI-generated content from the collected data sources."
            ),
            event(
                "attention", .explanation, paper: transformer,
                quote: "We compute the attention function on a set of queries simultaneously, packed together into a matrix Q, scaled by the square root of the key dimension."
            ),
            event(
                "dropout", .note, paper: transformer, page: 7,
                quote: "We apply dropout to the output of each sub-layer, before it is added to the sub-layer input and normalized.",
                text: "Residual dropout matters more than I expected."
            ),
            event(
                "beam", .question, paper: transformer, page: 8,
                quote: "We used beam search with a beam size of 4 and length penalty 0.6.",
                text: "Why does a length penalty help beam search?"
            ),
            event(
                "tokenizer", .translation, paper: mai, page: 3,
                quote: "The tokenizer uses byte-level BPE with a vocabulary of 200k entries covering code and multilingual text."
            ),
        ]
    }

    private let collapsePage = """
    Model collapse is a degenerative process affecting generations of learned generative models, in which the \
    data they generate end up polluting the training set of the next generation. As language models produce more \
    of the text on the web, pretraining corpora will increasingly contain synthetic data generated by earlier \
    models, and AI-generated content becomes hard to remove from collected sources.
    """

    private let optimizerPage = """
    We trained the models with the Adam optimizer and a learning rate schedule that increases linearly for the \
    first warmup steps and decreases thereafter proportionally to the inverse square root of the step number.
    """

    func testTermsDropFunctionWordsStemAndPairAdjacentWords() {
        let terms = LearningEchoText.terms(in: "We trained the language models on synthetic data, then AI-generated text.")
        XCTAssertNotNil(terms["train"], "“trained” is stemmed")
        XCTAssertNotNil(terms["model"])
        XCTAssertNotNil(terms["language model"], "Adjacent words form a pair")
        XCTAssertNotNil(terms["synthetic data"])
        XCTAssertNil(terms["data then"], "Punctuation ends a phrase")
        XCTAssertNil(terms["the"])
        XCTAssertEqual(terms["ai"], "AI", "Acronyms are kept and shown as written")
        XCTAssertNotNil(terms["ai generat"], "A hyphen joins a phrase")

        let chinese = LearningEchoText.terms(in: "我们在预训练期间不使用合成数据，会不会有问题？")
        XCTAssertTrue(chinese.keys.contains { $0.contains("合成") }, "\(chinese.keys.sorted())")
        XCTAssertTrue(chinese.keys.contains { $0.contains("训练") }, "\(chinese.keys.sorted())")
        XCTAssertNil(chinese["我们"])
        XCTAssertNil(chinese["会不会"], "Function words are not terms")
        XCTAssertFalse(chinese.keys.contains { $0.count < 2 }, "Single characters are not terms")
    }

    func testANoteInAnotherLanguageDoesNotDiluteItsPassage() {
        let noted = event(
            "noted", .note, paper: collapse,
            quote: "We find that indiscriminate use of model-generated content in training causes irreversible defects, where tails of the original distribution disappear.",
            text: "尾部分布先消失——这正是 MAI 不用合成数据的理由。我想在综述里专门写一段。"
        )
        let index = LearningEchoIndex(events: library + [noted], records: [])
        let page = "Trained on polluted data, models lose the tails of the original distribution, and AI-generated content in training compounds the defects."

        XCTAssertTrue(index.echoes(for: .init(text: page, paperID: current)).map(\.id).contains("noted"))
    }

    func testChineseFunctionWordsAloneAreNotAnEcho() {
        let asked = event(
            "asked", .question, paper: transformer, quote: "Label smoothing hurts perplexity.",
            text: "为什么会不会和这个有关？是不是因为我们的问题？"
        )
        let index = LearningEchoIndex(events: library + [asked], records: [])

        XCTAssertEqual(
            index.echoes(for: .init(text: "这个问题会不会是因为我们没有考虑？是不是有关？", writingID: UUID())),
            []
        )
    }

    func testRelatedPassageInAnotherPaperIsEchoed() {
        let index = LearningEchoIndex(events: library, records: [])

        let echoes = index.echoes(for: .init(text: collapsePage, paperID: collapse, pageIndex: 0))

        XCTAssertEqual(echoes.map(\.id), ["synthetic"])
        let echo = try? XCTUnwrap(echoes.first)
        XCTAssertGreaterThanOrEqual(echo?.score ?? 0, LearningEchoIndex.threshold)
        XCTAssertTrue(echo?.sharedTerms.contains("synthetic data") == true, "\(echo?.sharedTerms ?? [])")
    }

    func testUnrelatedPassageIsQuiet() {
        let index = LearningEchoIndex(events: library, records: [])

        XCTAssertEqual(index.echoes(for: .init(text: optimizerPage, paperID: current, pageIndex: 4)), [])
        XCTAssertEqual(index.echoes(for: .init(text: "", paperID: current)), [])
    }

    func testFewSharedGenericWordsAreNotAnEcho() {
        let index = LearningEchoIndex(events: library, records: [])
        let page = "Language models are trained on large data. We evaluate the models on several tasks."

        XCTAssertEqual(index.echoes(for: .init(text: page, paperID: current, pageIndex: 2)), [])
    }

    func testPassageOnScreenOrOnTheSamePageIsNotAnEcho() {
        let index = LearningEchoIndex(events: library, records: [])
        let page = "Intro. " + (library[0].quote ?? "") + " More text about model collapse and synthetic data."

        XCTAssertEqual(index.echoes(for: .init(text: page, paperID: current)), [], "The quote is on screen")
        XCTAssertEqual(
            index.echoes(for: .init(text: collapsePage, paperID: mai, pageIndex: 1)),
            [],
            "Same paper, same page"
        )
        XCTAssertEqual(
            index.echoes(for: .init(text: collapsePage, paperID: mai, pageIndex: 9)).map(\.id),
            ["synthetic"],
            "Earlier in the same paper still echoes"
        )
    }

    func testConceptNamedOnScreenEchoesItsEvidence() {
        let lookup = event(
            "kv", .explanation, paper: transformer, page: 5,
            quote: "Each decoding step reuses the cached keys and values of earlier tokens."
        )
        var record = PaperLearningRecord(paperID: transformer)
        record.items = [LearningRecordItem(
            id: "i1", kind: .concept, title: "KV cache", detail: "Stored keys and values", isResolved: false,
            isResolvedByUser: false, evidence: ["kv"],
            createdAt: Date(timeIntervalSince1970: 10), updatedAt: Date(timeIntervalSince1970: 10)
        )]
        let index = LearningEchoIndex(events: library + [lookup], records: [record])

        let echoes = index.echoes(for: .init(
            text: "Serving long contexts is limited by the size of the KV cache in GPU memory.",
            paperID: current,
            pageIndex: 0
        ))

        XCTAssertEqual(echoes.map(\.id), ["kv"])
        XCTAssertEqual(echoes.first?.conceptName, "KV cache")
    }

    func testOnePassageGivesOneCardPreferringTheReadersOwnWords() {
        let quote = library[0].quote
        let events = library + [
            event("turn0", .explanation, paper: mai, quote: quote, at: 200),
            event("turn1", .question, paper: mai, quote: quote, text: "Does this avoid model collapse?", at: 210),
        ]
        let index = LearningEchoIndex(events: events, records: [])

        let echoes = index.echoes(for: .init(text: collapsePage, paperID: collapse, pageIndex: 0))

        XCTAssertEqual(echoes.count, 1)
        XCTAssertEqual(echoes.first?.id, "turn1", "The question shares more with the page and is the reader's own words")
    }

    func testDismissedEventsAreSkipped() {
        let index = LearningEchoIndex(events: library, records: [])

        let echoes = index.echoes(
            for: .init(text: collapsePage, paperID: collapse, pageIndex: 0),
            excludingSubjects: ["synthetic"]
        )

        XCTAssertEqual(echoes, [])
    }

    func testAWritingIsNotRemindedOfItsOwnCitations() {
        let writing = UUID()
        let cited = event(
            "cited", .citation, paper: mai,
            quote: "Model collapse happens when synthetic data generated by language models pollutes the training set.",
            writingID: writing
        )
        let index = LearningEchoIndex(events: [cited] + library, records: [])
        let paragraph = "Synthetic data generated by language models can pollute the next training set: model collapse."

        XCTAssertFalse(index.echoes(for: .init(text: paragraph, writingID: writing)).map(\.id).contains("cited"))
        XCTAssertTrue(index.echoes(for: .init(text: paragraph, writingID: UUID())).map(\.id).contains("cited"))
    }

    func testSimilarityOnlyNudgesBorderlineMatches() {
        let index = LearningEchoIndex(events: library, records: [])
        let always = LearningEchoSimilarity { _, _ in 1 }

        XCTAssertEqual(
            index.echoes(for: .init(text: optimizerPage, paperID: current), similarity: always),
            [],
            "Meaning alone does not make an echo"
        )
        let plain = index.echoes(for: .init(text: collapsePage, paperID: collapse))
        let nudged = index.echoes(for: .init(text: collapsePage, paperID: collapse), similarity: always)
        XCTAssertEqual(nudged.first?.score ?? 0, (plain.first?.score ?? 0) + 0.1, accuracy: 0.0001)
    }

    // MARK: - Model

    private func makeModel(
        events: [LearningEvent],
        root: URL
    ) -> LearningEchoModel {
        LearningEchoModel(
            load: { ([], events) },
            revision: { 0 },
            similarity: nil,
            dismissals: LearningEchoDismissalStore(rootDirectory: root),
            delay: .milliseconds(10)
        )
    }

    private func temporaryRoot() throws -> URL {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString, isDirectory: true)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: root) }
        return root
    }

    private func waitUntil(_ condition: @escaping @MainActor () -> Bool, file: StaticString = #filePath, line: UInt = #line) async {
        for _ in 0..<200 where condition() == false {
            try? await Task.sleep(for: .milliseconds(10))
        }
        XCTAssertTrue(condition(), file: file, line: line)
    }

    func testModelFindsEchoesOnceTheScreenSettlesAndTracksWhatWasSeen() async throws {
        let model = makeModel(events: library, root: try temporaryRoot())

        model.reportReading(ReadingFocus(paperID: collapse, pageIndex: 0, text: optimizerPage))
        model.reportReading(ReadingFocus(paperID: collapse, pageIndex: 1, text: collapsePage))
        await waitUntil { model.reading?.focus.pageIndex == 1 }

        XCTAssertEqual(model.reading?.echoes.map(\.id), ["synthetic"])
        XCTAssertTrue(model.hasUnacknowledgedReadingEchoes)
        model.acknowledgeReadingEchoes()
        XCTAssertFalse(model.hasUnacknowledgedReadingEchoes)

        let echo = try XCTUnwrap(model.reading?.echoes.first)
        model.markOpened(echo)
        XCTAssertEqual(model.openedSubjects, ["synthetic"])

        model.reportReading(ReadingFocus(paperID: current, pageIndex: 0, text: "Another paper"))
        XCTAssertNil(model.reading, "Echoes of the previous paper are cleared at once")
    }

    func testDismissedEchoesStayDismissedForThatPaperOnly() async throws {
        let root = try temporaryRoot()
        let model = makeModel(events: library, root: root)
        model.reportReading(ReadingFocus(paperID: collapse, pageIndex: 1, text: collapsePage))
        await waitUntil { model.reading?.echoes.isEmpty == false }
        let echo = try XCTUnwrap(model.reading?.echoes.first)

        await model.dismiss(echo, context: LearningEchoModel.readingContext(collapse))
        XCTAssertEqual(model.reading?.echoes, [])

        let reopened = makeModel(events: library, root: root)
        reopened.reportReading(ReadingFocus(paperID: collapse, pageIndex: 2, text: collapsePage))
        await waitUntil { reopened.reading?.focus.pageIndex == 2 }
        XCTAssertEqual(reopened.reading?.echoes, [], "Remembered across launches")

        reopened.reportReading(ReadingFocus(paperID: current, pageIndex: 2, text: collapsePage))
        await waitUntil { reopened.reading?.focus.paperID == self.current }
        XCTAssertEqual(reopened.reading?.echoes.map(\.id), ["synthetic"], "Another paper still gets it")
    }

    func testWritingEchoesSkipPassagesTheWritingAlreadyQuotes() async throws {
        let model = makeModel(events: library, root: try temporaryRoot())
        let writing = UUID()
        let paragraph = "Model collapse: synthetic data generated by language models pollutes pretraining sources."

        model.reportWriting(writingID: writing, paragraph: paragraph, fullText: paragraph)
        await waitUntil { model.writing != nil }
        XCTAssertEqual(model.writing?.echoes.map(\.id), ["synthetic"])

        let quoted = paragraph + "\n\n> " + (library[0].quote ?? "")
        model.reportWriting(writingID: writing, paragraph: paragraph + " ", fullText: quoted)
        await waitUntil { model.writing?.echoes.isEmpty == true }
    }

    // MARK: - Marks beside paragraphs (v2)

    private var collapseBlocks: [ReadingBlock] {
        [
            ReadingBlock(id: "intro", text: "Generative models are now trained at scale on web text."),
            ReadingBlock(id: "collapse", text: collapsePage),
            ReadingBlock(id: "optimizer", text: optimizerPage),
        ]
    }

    func testEachEchoIsPlacedBesideTheParagraphSharingItsWords() {
        let index = LearningEchoIndex(events: library, records: [])
        let text = collapseBlocks.map(\.text).joined(separator: "\n")
        let echoes = index.echoes(for: .init(text: text, paperID: collapse, pageIndex: 0))

        XCTAssertEqual(echoes.map(\.id), ["synthetic"], "The screen decides what echoes")
        XCTAssertEqual(index.placements(of: echoes, in: collapseBlocks), ["collapse": ["synthetic"]])
        XCTAssertEqual(index.placements(of: echoes, in: []), [:])
        XCTAssertEqual(
            index.placements(of: echoes, in: [ReadingBlock(id: "other", text: "Nothing in common here.")]),
            [:],
            "A paragraph that shares nothing gets no mark"
        )
    }

    func testAConceptEchoIsPlacedWhereTheConceptIsNamed() {
        let lookup = event("kv", .explanation, paper: transformer, page: 5, quote: "Each decoding step reuses cached keys.")
        var record = PaperLearningRecord(paperID: transformer)
        record.items = [LearningRecordItem(
            id: "i1", kind: .concept, title: "KV cache", detail: nil, isResolved: false, isResolvedByUser: false,
            evidence: ["kv"], createdAt: Date(timeIntervalSince1970: 1), updatedAt: Date(timeIntervalSince1970: 1)
        )]
        let index = LearningEchoIndex(events: library + [lookup], records: [record])
        let blocks = [
            ReadingBlock(id: "a", text: "We serve long contexts on a single GPU."),
            ReadingBlock(id: "b", text: "Memory is dominated by the KV cache at long context lengths."),
        ]
        let echoes = index.echoes(for: .init(text: blocks.map(\.text).joined(separator: " "), paperID: current))

        XCTAssertEqual(echoes.map(\.id), ["kv"])
        XCTAssertEqual(index.placements(of: echoes, in: blocks), ["b": ["kv"]])
    }

    func testMarksFollowTheScreenAndStepBackOnceSeen() async throws {
        let model = makeModel(events: library, root: try temporaryRoot())
        let attachment = UUID()
        final class Received {
            var marks: [[LearningEchoMark]] = []
        }
        let owner = Received()
        model.observeMarks(owner: owner, paperID: collapse, attachmentID: attachment) { owner.marks.append($0) }
        var received: [[LearningEchoMark]] { owner.marks }
        XCTAssertEqual(received, [[]], "Observing reports the current marks at once")

        model.reportReading(ReadingFocus(
            paperID: collapse, attachmentID: attachment, pageIndex: 1,
            text: collapseBlocks.map(\.text).joined(separator: "\n"), blocks: collapseBlocks
        ))
        await waitUntil { received.count == 2 }
        XCTAssertEqual(received.last, [LearningEchoMark(blockID: "collapse", count: 1, isSeen: false)])
        XCTAssertEqual(model.marks(paperID: collapse, attachmentID: UUID()), [], "Another attachment has no marks")

        let echo = try XCTUnwrap(model.reading?.echoes.first)
        model.markOpened(echo)
        XCTAssertEqual(received.last, [LearningEchoMark(blockID: "collapse", count: 1, isSeen: true)])
        model.markOpened(echo)
        XCTAssertEqual(received.count, 3, "Nothing changed, nothing is sent")

        model.stopObservingMarks(owner: owner)
        model.forget(echo)
        XCTAssertEqual(received.count, 3)
        XCTAssertEqual(model.marks(paperID: collapse, attachmentID: attachment), [])
    }

    func testTheFanShowsTheParagraphsEchoesAndClosesWhenTheScreenMoves() async throws {
        let model = makeModel(events: library, root: try temporaryRoot())
        let focus = ReadingFocus(
            paperID: collapse, attachmentID: UUID(), pageIndex: 1,
            text: collapseBlocks.map(\.text).joined(separator: "\n"), blocks: collapseBlocks
        )
        model.reportReading(focus)
        await waitUntil { model.reading?.echoes.isEmpty == false }

        model.openFan(paperID: collapse, blockID: "optimizer", rect: .zero)
        XCTAssertNil(model.fan, "A paragraph without echoes has no fan")
        model.openFan(paperID: current, blockID: "collapse", rect: .zero)
        XCTAssertNil(model.fan, "Not for another paper")
        model.openFan(paperID: collapse, blockID: "collapse", rect: CGRect(x: 10, y: 20, width: 18, height: 18))
        XCTAssertEqual(model.fan?.echoes.map(\.id), ["synthetic"])
        XCTAssertEqual(model.fan?.rect.minY, 20)

        model.reportReading(focus)
        XCTAssertNotNil(model.fan, "The same screen keeps it open")
        var moved = focus
        moved.pageIndex = 2
        model.reportReading(moved)
        XCTAssertNil(model.fan, "Scrolling closes it")

        model.reportReading(focus)
        await waitUntil { model.reading?.focus == focus }
        model.openFan(paperID: collapse, blockID: "collapse", rect: .zero)
        let echo = try XCTUnwrap(model.fan?.echoes.first)
        await model.dismiss(echo, context: LearningEchoModel.readingContext(collapse))
        XCTAssertNil(model.fan, "Dismissing its last card closes it")
        XCTAssertEqual(model.reading?.placements, [:])
    }
